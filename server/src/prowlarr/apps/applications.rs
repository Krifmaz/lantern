/// The "reject blocklisted torrent hashes" switch, at `order`.
const fn reject_field(order: i64) -> FieldSpec {
    FieldSpec {
        order,
        name: "syncRejectBlocklistedTorrentHashesWhileGrabbing",
        label: "ApplicationSettingsSyncRejectBlocklistedTorrentHashes",
        help_text: Some("ApplicationSettingsSyncRejectBlocklistedTorrentHashesHelpText"),
        kind: ValueKind::Bool,
        field_type: FieldType::Checkbox,
        advanced: true,
        default: Initial::Bool(false),
        ..FieldSpec::BASE
    }
}

/// Joins an app's common fields with its own.
const fn with<const A: usize, const B: usize, const N: usize>(a: [FieldSpec; A], b: [FieldSpec; B]) -> [FieldSpec; N] {
    let mut out = [FieldSpec::BASE; N];
    let mut i = 0;
    while i < A {
        out[i] = a[i];
        i += 1;
    }
    let mut j = 0;
    while j < B {
        out[A + j] = b[j];
        j += 1;
    }
    out
}

