/// The checks of Sonarr's and Lidarr's settings: both addresses and an API key.
fn validate_urls_and_key(s: &Map<String, Value>) -> Vec<ProviderFailure> {
    [check_url(s, "baseUrl", "BaseUrl"), check_url(s, "prowlarrUrl", "ProwlarrUrl"), check_not_empty(s, "apiKey", "ApiKey")]
        .into_iter()
        .flatten()
        .collect()
}

/// The checks of the other apps' settings: also at least one sync category.
fn validate_with_categories(s: &Map<String, Value>) -> Vec<ProviderFailure> {
    let mut out = validate_urls_and_key(s);
    out.extend(check_not_empty(s, "syncCategories", "SyncCategories"));
    out
}

