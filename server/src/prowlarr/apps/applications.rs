/// How Lantern talks to an app: Sonarr and its siblings, or Mylar and LazyLibrarian.
#[derive(Debug, Clone, Copy)]
pub enum Client {
    /// Sonarr, Radarr, Lidarr, Readarr, Whisparr.
    Arr(&'static arr::Spec),
    /// Mylar, LazyLibrarian.
    Nab(&'static nab::Spec),
}

impl Client {
    /// The client of an implementation.
    pub fn of(implementation: &str) -> Option<Client> {
        Some(match implementation.to_lowercase().as_str() {
            "sonarr" => Client::Arr(&arr::SONARR),
            "radarr" => Client::Arr(&arr::RADARR),
            "lidarr" => Client::Arr(&arr::LIDARR),
            "readarr" => Client::Arr(&arr::READARR),
            "whisparr" => Client::Arr(&arr::WHISPARR),
            "mylar" => Client::Nab(&nab::MYLAR),
            "lazylibrarian" => Client::Nab(&nab::LAZYLIBRARIAN),
            _ => return None,
        })
    }

    /// The app's indexers that point at Lantern.
    pub async fn mappings(self, ctx: &Ctx) -> Result<Vec<RemoteMap>, super::http::HttpError> {
        match self {
            Client::Arr(s) => arr::mappings(s, ctx).await,
            Client::Nab(s) => nab::mappings(s, ctx).await,
        }
    }

    /// Adds an indexer to the app.
    pub async fn add(self, ctx: &Ctx, ix: &SyncIndexer) -> Result<(), super::http::HttpError> {
        match self {
            Client::Arr(s) => arr::add(s, ctx, ix).await,
            Client::Nab(s) => nab::add(s, ctx, ix).await,
        }
    }

    /// Brings an indexer in the app up to date.
    pub async fn update(self, ctx: &Ctx, ix: &SyncIndexer, force: bool) -> Result<(), super::http::HttpError> {
        match self {
            Client::Arr(s) => arr::update(s, ctx, ix, force).await,
            Client::Nab(s) => nab::update(s, ctx, ix, force).await,
        }
    }

    /// Removes an indexer from the app.
    pub async fn remove_indexer(self, ctx: &Ctx, id: i64) -> Result<(), super::http::HttpError> {
        match self {
            Client::Arr(s) => arr::remove_indexer(s, ctx, id).await,
            Client::Nab(s) => nab::remove_indexer(s, ctx, id).await,
        }
    }

    /// Tests the app.
    pub async fn test(self, ctx: &Ctx) -> Vec<ProviderFailure> {
        match self {
            Client::Arr(s) => arr::test(s, ctx).await,
            Client::Nab(s) => nab::test(s, ctx).await,
        }
    }
}

/// The applications family.
pub struct Applications;

impl Family for Applications {
    const RESOURCE: &'static str = "applications";
    const TABLE: &'static str = "prowlarr_applications";
    const MODEL: &'static str = "ApplicationDefinition";

    fn implementations() -> &'static [Implementation] {
        &IMPLEMENTATIONS
    }

    fn enabled(def: &Definition) -> bool {
        SyncLevel::of(def) != SyncLevel::Disabled
    }

    fn extra_from_body(body: &Map<String, Value>) -> Result<Map<String, Value>, ApiError> {
        let level = SyncLevel::parse(prop(body, "syncLevel").unwrap_or(&Value::Null))?;
        Ok([("syncLevel".to_string(), json!(level.name()))].into_iter().collect())
    }

    fn extra_json(def: &Definition, out: &mut Map<String, Value>) {
        let level = SyncLevel::of(def);
        out.insert("syncLevel".into(), json!(level.name()));
        out.insert("enable".into(), json!(level != SyncLevel::Disabled));
    }

    fn default_extra() -> Map<String, Value> {
        [("syncLevel".to_string(), json!(SyncLevel::FullSync.name()))].into_iter().collect()
    }

    fn bulk_extra(def: &mut Definition, body: &Map<String, Value>) -> Result<(), ApiError> {
        if let Some(v) = prop(body, "syncLevel").filter(|v| !v.is_null()) {
            def.extra.insert("syncLevel".into(), json!(SyncLevel::parse(v)?.name()));
        }
        Ok(())
    }

    async fn test(st: &AppState, def: &Definition) -> Vec<ProviderFailure> {
        let Some(client) = Client::of(&def.implementation) else { return Vec::new() };
        let ctx = Ctx { st: st.clone(), app: def.clone(), api_key: st.settings.str("api_key") };
        let failures = client.test(&ctx).await;
        if def.id != 0 {
            if failures.iter().all(|f| f.is_warning) {
                status::APPLICATION_STATUS.record_success(&st.db, def.id);
            } else {
                status::APPLICATION_STATUS.record_failure(&st.db, def.id, 0.0, true);
            }
        }
        failures
    }

    fn added(st: &AppState, def: &Definition) {
        let (st, def) = (st.clone(), def.clone());
        tokio::spawn(async move { sync::app_saved(&st, &def).await });
    }

    fn updated(st: &AppState, def: &Definition) {
        Self::added(st, def);
    }

    fn deleted(st: &AppState, id: i64) {
        let _ = sync::delete_maps_for_app(&st.db, id);
        let _ = status::APPLICATION_STATUS.delete(&st.db, id);
    }

    fn bulk_updated(_st: &AppState, _defs: &[Definition]) {}

    fn bulk_deleted(st: &AppState, ids: &[i64]) {
        // Prowlarr's housekeeping removes what deleted apps leave behind
        for id in ids {
            Self::deleted(st, *id);
        }
    }

    async fn request_action(_st: &AppState, _def: &Definition, _name: &str, _query: &HashMap<String, String>) -> Result<Value, ApiError> {
        Ok(Value::Null)
    }
}

/// The table that remembers which imported apps were taken over.
pub const TAKEN_SCHEMA: &str = "CREATE TABLE IF NOT EXISTS prowlarr_imported_apps_taken (imported_id INTEGER PRIMARY KEY);";

/// Takes over the apps the import kept (`imported_apps`, from a Prowlarr backup or API): each becomes an
/// application with its address, API key, Prowlarr server, sync level, tags and categories, once. One with a name
/// already used, or of an app Lantern doesn't know, is left (and logged).
pub fn take_imported(st: &AppState) {
    let db = &st.db;
    let Ok(rows) =
        db.query("SELECT * FROM imported_apps WHERE id NOT IN (SELECT imported_id FROM prowlarr_imported_apps_taken) ORDER BY id", p![])
    else {
        return;
    };
    for r in rows {
        let _ = db.execute("INSERT OR IGNORE INTO prowlarr_imported_apps_taken (imported_id) VALUES (?)", p![r.i("id")]);
        let name = r.s("name");
        let Some(imp) = provider::implementation_of::<Applications>(&r.s("kind")) else {
            tracing::warn!("Import: the app {name} ({}) is not one Lantern syncs, so it was left out.", r.s("kind"));
            continue;
        };
        let taken = provider::all::<Applications>(db).unwrap_or_default().iter().any(|d| d.label().eq_ignore_ascii_case(&name));
        if taken {
            tracing::warn!("Import: an application named {name} is already there, so the imported one was left out.");
            continue;
        }
        let mut settings = imp.defaults();
        let mut put = |k: &str, v: String| {
            if !v.trim().is_empty() {
                settings.insert(k.into(), json!(v));
            }
        };
        put("baseUrl", r.s("base_url"));
        put("apiKey", r.s("api_key"));
        put("prowlarrUrl", r.s("source_url"));
        let cats: Vec<i64> = serde_json::from_str(&r.s("categories")).unwrap_or_default();
        if !cats.is_empty() {
            settings.insert("syncCategories".into(), json!(cats));
        }
        let level = match r.s("sync_level").as_str() {
            "disabled" => SyncLevel::Disabled,
            "add_remove" => SyncLevel::AddOnly,
            _ => SyncLevel::FullSync,
        };
        let mut tags = Vec::new();
        for label in super::super::tags::labels_of(&r.s("tags")) {
            let _ = db.execute("INSERT OR IGNORE INTO prowlarr_tags (label) VALUES (?)", p![label.clone()]);
            if let Ok(Some(t)) = db.one("SELECT id FROM prowlarr_tags WHERE label=?", p![label]) {
                tags.push(t.i("id"));
            }
        }
        let mut def = Definition {
            id: 0,
            name: Some(name.clone()),
            implementation: imp.implementation.into(),
            config_contract: imp.config_contract.into(),
            settings,
            tags,
            extra: [("syncLevel".to_string(), json!(level.name()))].into_iter().collect(),
        };
        match provider::insert::<Applications>(db, &def) {
            Ok(id) => {
                def.id = id;
                tracing::info!("Import: the app {name} now syncs from Lantern ({}).", level.name());
                Applications::added(st, &def);
            }
            Err(e) => tracing::warn!("Import: the app {name} couldn't be taken over: {}", e.detail),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_app_has_prowlarrs_settings_and_defaults() {
        let sonarr = provider::implementation_of::<Applications>("Sonarr").unwrap();
        let d = sonarr.defaults();
        assert_eq!(d["prowlarrUrl"], "http://localhost:9696");
        assert_eq!(d["baseUrl"], "http://localhost:8989");
        assert_eq!(d["syncCategories"], json!([5000, 5010, 5020, 5030, 5040, 5045, 5050, 5090]));
        assert_eq!(d["animeSyncCategories"], json!([5070]));
        assert_eq!(d["syncAnimeStandardFormatSearch"], true);
        assert_eq!(d["syncRejectBlocklistedTorrentHashesWhileGrabbing"], false);
        assert!(d["apiKey"].is_null());
        assert_eq!(sonarr.fields[2].help_text, Some("The ApiKey generated by Sonarr in Settings/General"));
        let mylar = provider::implementation_of::<Applications>("mylar").unwrap();
        assert_eq!(mylar.defaults()["syncCategories"], json!([7030]));
        assert_eq!(mylar.fields.len(), 6);
        assert_eq!(provider::implementation_of::<Applications>("LazyLibrarian").unwrap().defaults()["baseUrl"], "http://localhost:5299");
    }

    #[test]
    fn settings_checks_follow_each_validator() {
        let sonarr = provider::implementation_of::<Applications>("Sonarr").unwrap();
        let mut s = sonarr.defaults();
        let f = (sonarr.validate)(&s);
        assert_eq!(f.len(), 1);
        assert_eq!((f[0].property.as_str(), f[0].message.as_str()), ("ApiKey", "'Api Key' must not be empty."));
        s.insert("apiKey".into(), json!("k"));
        s.insert("syncCategories".into(), json!([]));
        assert!((sonarr.validate)(&s).is_empty());
        let radarr = provider::implementation_of::<Applications>("Radarr").unwrap();
        assert_eq!((radarr.validate)(&s)[0].property, "SyncCategories");
        s.insert("baseUrl".into(), json!("/sonarr"));
        let f = (sonarr.validate)(&s);
        assert_eq!(f[0].json()["errorMessage"], "Invalid Url: '/sonarr'");
    }

    #[test]
    fn sync_levels_read_like_prowlarrs_enum() {
        assert_eq!(SyncLevel::parse(&json!("fullSync")).unwrap(), SyncLevel::FullSync);
        assert_eq!(SyncLevel::parse(&json!("AddOnly")).unwrap(), SyncLevel::AddOnly);
        assert_eq!(SyncLevel::parse(&json!(0)).unwrap(), SyncLevel::Disabled);
        assert_eq!(SyncLevel::parse(&Value::Null).unwrap(), SyncLevel::Disabled);
        assert!(SyncLevel::parse(&json!("sometimes")).is_err());
    }
}
